-- RAZAK STORE test schema (Supabase / PostgreSQL)
create table if not exists public.webhook_events (
  id bigint generated by default as identity primary key,
  event_id text unique not null,
  source text not null default 'sociabuzz_shop',
  payload jsonb not null default '{}'::jsonb,
  received_at timestamptz not null default now(),
  processed boolean not null default false
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  category text,
  price integer not null check (price >= 0),
  delivery_asset_path text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_code text unique not null,
  buyer_name text not null,
  buyer_email text not null,
  total integer not null check (total >= 0),
  status text not null default 'pending' check (status in ('pending','paid','failed','expired','fulfilled')),
  payment_provider text,
  provider_transaction_id text unique,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id),
  product_name text not null,
  unit_price integer not null,
  quantity integer not null check (quantity > 0)
);

